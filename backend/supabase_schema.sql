create table if not exists public.fare_predictions (
    id bigint generated by default as identity primary key,
    airline text not null,
    source_city text not null,
    destination_city text not null,
    departure_time text not null,
    arrival_time text not null,
    stops text not null,
    flight_class text not null,
    duration double precision not null,
    days_left integer not null,
    predicted_fare double precision not null
);

create table if not exists public.delay_predictions (
    id bigint generated by default as identity primary key,
    month integer not null,
    day integer not null,
    daysofweek integer not null,
    origin_airport text not null,
    destination_airport text not null,
    scheduled_departure integer not null,
    scheduled_arrival integer not null,
    departure_delay integer not null,
    air_time double precision not null,
    distance integer not null,
    predicted_delay double precision not null
);

alter table public.fare_predictions enable row level security;
alter table public.delay_predictions enable row level security;

grant usage on schema public to service_role;
grant select, insert on public.fare_predictions to service_role;
grant select, insert on public.delay_predictions to service_role;
grant usage, select on all sequences in schema public to service_role;
